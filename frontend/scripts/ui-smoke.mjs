import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'

const base = process.env.UI_BASE_URL || 'http://127.0.0.1:5173'
const user = process.env.UI_TEST_USER || 'admin'
const password = process.env.UI_TEST_PASSWORD
const institution = process.env.UI_TEST_INSTITUTION || 'uphn'
assert(password, 'Define UI_TEST_PASSWORD sin guardarla en el repositorio')
const output = process.env.UI_ARTIFACTS || '/tmp/campusflow-ui-artifacts'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, locale: 'es-HN', reducedMotion: 'reduce', acceptDownloads: true })
const page = await context.newPage()
page.setDefaultTimeout(60000)
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
page.on('response', (response) => { if (response.url().startsWith(`${base}/api/`) && response.status() >= 500) errors.push(`HTTP ${response.status()} ${new URL(response.url()).pathname}`) })
async function screenshot(name) { await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(250); await page.screenshot({ path: `${output}/${name}.png`, fullPage: true }) }
async function noOverflow() { assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'La pagina desborda horizontalmente') }
async function navigate(label) { await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: label, exact: true }).click() }
async function json(path) { const response = await context.request.get(`${base}/api${path}`, { headers: { 'X-Institution-Slug': institution } }); assert.equal(response.status(), 200, path); return response.json() }
try {
  await page.goto(`${base}/iniciar-sesion`)
  await page.getByLabel('Universidad', { exact: true }).fill(institution)
  await page.getByLabel('Usuario', { exact: true }).fill(user)
  await page.locator('input[type=password]').fill(password)
  await page.getByRole('button', { name: 'Ingresar al campus' }).click()
  await page.getByRole('heading', { name: 'Resumen académico', exact: true }).waitFor()
  await page.getByRole('region', { name: 'Indicadores académicos' }).waitFor()
  const summary = await json('/dashboard/resumen')
  const metricText = await page.locator('.academic-metrics').innerText()
  assert(metricText.includes(summary.estudiantes.activos.toLocaleString('es-HN')), 'Los estudiantes coinciden con la API')
  assert.equal(await page.locator('.academic-dashboard img').count(), 0)
  await screenshot('01-resumen'); await noOverflow()
  await navigate('Docentes')
  await page.locator('tbody tr').first().getByRole('button', { name: 'Acciones de docente' }).waitFor()
  const firstRow = page.locator('tbody tr').first()
  const teacherCode = await firstRow.locator('td').first().innerText()
  await firstRow.getByRole('button', { name: 'Materias y secciones' }).click()
  await page.getByRole('dialog').waitFor()
  assert((await page.getByRole('dialog').innerText()).includes('Contrato:'))
  await screenshot('02-carga-docente'); await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await firstRow.getByRole('button', { name: 'Acciones de docente' }).click()
  await page.getByRole('menuitem', { name: 'Ver carnet' }).click()
  await page.getByRole('dialog', { name: /^Carnet de/ }).waitFor()
  assert((await page.getByRole('dialog').innerText()).includes(teacherCode))
  await screenshot('03-carnet-docente'); await page.getByRole('button', { name: 'Cerrar carnet' }).click()
  await page.getByRole('button', { name: 'Filtros', exact: true }).click()
  await page.getByLabel('Filtrar por estado', { exact: true }).selectOption('inactivo')
  await page.waitForResponse((response) => response.url().includes('/docentes/') && response.request().method() === 'GET').catch(() => {})
  await page.getByRole('button', { name: 'Limpiar', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar filtros' }).click()
  await page.getByRole('button', { name: 'Página siguiente', exact: true }).click()
  await page.locator('nav[aria-label="Paginación de docentes"] [aria-current=page]').filter({ hasText: '2' }).waitFor()
  await page.getByRole('button', { name: 'Página anterior', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Buscar docentes' }).fill(teacherCode)
  await page.locator('tbody tr').first().getByText(teacherCode, { exact: true }).waitFor()
  await page.getByRole('searchbox', { name: 'Buscar docentes' }).fill('')
  await page.locator('tbody tr').nth(9).waitFor()
  await screenshot('04-docentes'); await noOverflow()
  await navigate('Reportes')
  await page.getByRole('heading', { name: 'Reportes académicos', exact: true }).waitFor()
  await screenshot('05-reportes-inicial')
  await page.getByRole('button', { name: 'Consultar datos', exact: true }).click()
  await page.locator('.academic-report-results tbody tr').first().waitFor()
  assert((await page.locator('.academic-report-results').innerText()).includes('registros'))
  await screenshot('06-reportes-resultados')
  await page.getByRole('button', { name: 'Exportar', exact: true }).click()
  await page.getByRole('dialog', { name: 'Vista previa de exportación' }).waitFor()
  await screenshot('07-exportacion')
  await page.getByLabel('Formato de exportación').selectOption('csv')
  await page.getByRole('button', { name: 'Ver contenido', exact: true }).click()
  await page.getByRole('dialog', { name: 'Vista previa de Estudiantes', exact: true }).waitFor()
  assert((await page.getByRole('dialog', { name: 'Vista previa de Estudiantes', exact: true }).locator('pre').innerText()).length > 50)
  await page.getByRole('button', { name: 'Cerrar vista previa' }).click()
  await page.getByLabel('Formato de exportación').selectOption('xlsx')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar reporte (.xlsx)', exact: true }).click()
  const download = await downloadPromise
  assert(download.suggestedFilename().endsWith('.xlsx'))
  assert.equal(await download.failure(), null)
  await navigate('Actividad reciente')
  await page.getByLabel('Filtrar por módulo').selectOption('aulas')
  await page.locator('.academic-activity-count').first().waitFor()
  await screenshot('08-actividad')
  await page.getByLabel('Buscar usuario').fill('sin-coincidencias-ui-verificacion')
  await page.getByRole('heading', { name: 'No se encontraron movimientos' }).waitFor()
  await screenshot('09-actividad-vacia')
  await page.getByRole('button', { name: 'Limpiar filtros' }).click()
  await page.locator('.academic-activity-count').first().waitFor()
  await page.getByRole('button', { name: 'Abrir menu de cuenta' }).click()
  assert.equal(await page.getByText('Modo oscuro', { exact: true }).count(), 0)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('html.dark').count(), 0)
  for (const [label, name] of [['Dashboard', 'resumen'], ['Docentes', 'docentes'], ['Reportes', 'reportes'], ['Actividad reciente', 'actividad']]) {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
    await navigate(label)
    await page.waitForTimeout(1000)
    await noOverflow(); await screenshot(`10-mobile-${name}`)
  }
  assert.deepEqual(errors, [], 'Sin errores de JavaScript ni errores HTTP 500')
  console.log(JSON.stringify({ status: 'passed', checks: ['login UI', 'resumen con Supabase', 'docentes y filtros', 'carga y carnet', 'reportes Worker', 'vista CSV', 'descarga Excel', 'actividad y vacio', 'tema claro', 'responsive 390px'], artifacts: output }))
} catch (error) { await screenshot('failure'); throw error } finally { await browser.close() }
